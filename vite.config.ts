import { defineConfig, Plugin } from 'vite';
import react from '@vitejs/plugin-react';

/**
 * Samsung Tizen (TVs, The Freestyle) loads packaged apps from the local file system, where Chromium blocks
 * <script type="module" crossorigin> → black screen. For production builds we emit one classic script instead
 * (also fine for the website).
 */
const tizenClassicScript = (): Plugin => ({
  name: 'tizen-classic-script',
  apply: 'build',
  transformIndexHtml: {
    order: 'post',
    handler: (html) =>
      html
        .replace(/<script type="module" crossorigin src="([^"]+)"><\/script>/g, '<script defer src="$1"></script>')
        .replace(/<link rel="stylesheet" crossorigin href=/g, '<link rel="stylesheet" href=')
        .replace(/<link rel="modulepreload"[^>]*>/g, '')
  }
});

/**
 * Website build (`npm run build:web` → dist-web/): no Tizen packaging files, plus a web app manifest so
 * Chrome / Edge on a laptop offer "Install Yudia" (own window, taskbar icon).
 */
const websiteBuild = (): Plugin => ({
  name: 'yudia-website',
  apply: 'build',
  transformIndexHtml: (html) =>
    html.replace(
      '</head>',
      '    <link rel="manifest" href="./manifest.webmanifest" />\n    <meta name="theme-color" content="#07090e" />\n  </head>'
    ),
  async generateBundle(_options, bundle) {
    const { readFile } = await import('node:fs/promises');
    // Offline copy of the app (service worker): opens with no connection so downloads can be played.
    // Precaches this build's files; old versions are dropped when a new build is uploaded.
    const files = Object.keys(bundle).filter((n) => !n.endsWith('.map'));
    const precache = ['./', './index.html', './favicon.svg', './manifest.webmanifest', ...files.map((n) => './' + n)];
    const version = files.sort().join('|').split('').reduce((h, c) => (h * 31 + c.charCodeAt(0)) >>> 0, 7).toString(36);
    this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorkerSource(version, [...new Set(precache)]) });
    this.emitFile({ type: 'asset', fileName: 'favicon.svg', source: await readFile('public/favicon.svg') });
    // For Apache web hosts (most shared hosting). Ignored by other servers.
    this.emitFile({
      type: 'asset',
      fileName: '.htaccess',
      source: [
        '# Yudia website',
        '# Always HTTPS (the Jellyfin server is HTTPS; an http page would also work, but https is safer)',
        '<IfModule mod_rewrite.c>',
        '  RewriteEngine On',
        '  RewriteCond %{HTTPS} !=on',
        '  RewriteCond %{HTTP:X-Forwarded-Proto} !=https',
        '  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]',
        '</IfModule>',
        '',
        'AddType application/manifest+json .webmanifest',
        'AddType image/svg+xml .svg',
        '',
        '<IfModule mod_headers.c>',
        '  # index.html / manifest / sw.js: always re-check so a new version shows up right after upload',
        '  <FilesMatch "(\\.(html|webmanifest)|^sw\\.js)$">',
        '    Header set Cache-Control "no-cache"',
        '  </FilesMatch>',
        '  # Built files have a content hash in their name: cache for a year',
        '  <FilesMatch "\\.(js|css)$">',
        '    Header set Cache-Control "public, max-age=31536000, immutable"',
        '  </FilesMatch>',
        '</IfModule>',
        '',
        '<IfModule mod_deflate.c>',
        '  AddOutputFilterByType DEFLATE text/html text/css application/javascript application/manifest+json image/svg+xml',
        '</IfModule>',
        ''
      ].join('\n')
    });
    this.emitFile({
      type: 'asset',
      fileName: 'manifest.webmanifest',
      source: JSON.stringify(
        {
          name: 'Yudia',
          short_name: 'Yudia',
          description: 'Your Jellyfin library — movies, series, live TV and music.',
          start_url: './',
          scope: './',
          display: 'standalone',
          background_color: '#07090e',
          theme_color: '#07090e',
          icons: [{ src: './favicon.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'any' }]
        },
        null,
        2
      )
    });
  }
});

/** Service worker for the website (see src/offline/registerServiceWorker.ts). Never touches the Jellyfin server. */
function serviceWorkerSource(version: string, precache: string[]): string {
  return `// Yudia offline app shell — generated by the website build
const APP_CACHE = 'yudia-app-${version}';
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(APP_CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      // only old app copies — never the downloads (yudia-offline-media-*)
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('yudia-app-') && k !== APP_CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // Jellyfin server & CDNs: untouched
  if (url.pathname.includes('/__yudia/')) return;

  // Pages: newest version when online, the saved copy when offline
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(APP_CACHE).then((c) => c.put('./index.html', copy));
          return res;
        })
        .catch(() => caches.match('./index.html', { ignoreSearch: true }).then((r) => r || caches.match('./')))
    );
    return;
  }
  // Built files (hashed names): saved copy first
  event.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req)));
});
`;
}

// https://vitejs.dev/config/
export default defineConfig(({ mode }) => {
  const web = mode === 'web';
  return {
    plugins: [react(), tizenClassicScript(), ...(web ? [websiteBuild()] : [])],
    // The website never gets public/ (Tizen config.xml, project file, TV icon); websiteBuild() adds what it needs.
    publicDir: web ? false : 'public',
    // Pre-filled server: the owner's on the TV build, none on the website (friends enter their own).
    define: { __YUDIA_DEFAULT_SERVER__: JSON.stringify(web ? '' : 'https://jellyfin.example.com'), __YUDIA_WEB__: JSON.stringify(web) },
    base: './', // relative paths: works from a Tizen package and from any folder on a web server
    server: {
      port: 3000,
      host: true
    },
    build: {
      target: 'chrome77', // Tizen 6.0+ (Chromium 76+). The Freestyle: 1st gen Tizen 6.5 (Chromium 85), 2nd gen Tizen 7 (Chromium 94). No CSS 'inset'/'aspect-ratio' (need 87+/88+).
      outDir: web ? 'dist-web' : 'dist',
      assetsDir: 'assets',
      modulePreload: false,
      rollupOptions: {
        // Single self-contained classic bundle (no ES module loading at runtime)
        output: { format: 'iife', inlineDynamicImports: true }
      }
    }
  };
});
